interface Mirror {
  /** Площадка: consultant / legalacts / garant / нтр.рф / ведомство / прочее. */
  kind: string;
  /** Полный URL, проверенный открытием. */
  url: string;
  /** Что по этой ссылке видно (статус открытия + содержимое). */
  note: string;
}

interface NptlCard {
  /** Официальное название нацпроекта. */
  name: string;
  /** Реквизиты документа, утверждающего паспорт (вид, номер, дата), или «не найдено». */
  passportRequisites: string;
  /** Федеральные проекты в составе нацпроекта. */
  fps: string[];
  /** Какие целевые показатели паспорта публично доступны и где. */
  indicators: string;
  /** Уровень декомпозиции, достижимый из открытых источников: рамка / показатели / задачи / барьеры. */
  decomposition: string;
  /** Проверенные зеркала и источники текста. */
  mirrors: Mirror[];
  /** Отраслевые НПА, стратегии, дорожные карты направления (с реквизитами/ссылками). */
  industryDocs: string[];
  /** Чего не хватает до связки «криттехнология → барьер → проектный вызов». */
  gaps: string[];
}

interface Verification {
  /** true — реквизиты подтверждены двумя независимыми копиями. */
  confirmed: boolean;
  /** Верифицированные реквизиты или объяснение, почему не подтверждено. */
  requisites: string;
  /** Где проверено: какие площадки и что совпало. */
  checkedWith: string;
}

interface GapGroup {
  /** Нацпроект. */
  nptl: string;
  /** Готовые запросы веера уровня 2. */
  queries: string[];
}

interface GapPlan {
  groups: GapGroup[];
  /** Что закрывает веер, а что доступно только человеку. */
  comment: string;
}

interface WorkflowReport {
  conclusion: string;
  findings: {
    /** Нацпроект или его раздел. */
    where: string;
    what: string;
    evidence: string;
    status: "verified" | "unconfirmed";
    severity: "low" | "medium" | "high";
  }[];
  verified: string[];
  notCovered: string[];
}

