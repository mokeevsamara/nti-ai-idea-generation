const gapPlanner = agent("добор-уровня-2", {
  system:
    "Ты — методолог дип-ресерча. Составляешь готовый веер запросов следующего уровня по пробелам, с привязкой к реально доступным площадкам. " +
    "Запросы формулируешь так, чтобы их можно было выполнить веб-поиском без изменений. Файлы не редактируешь.",
});
const gapPlan = await gapPlanner.ask<GapPlan>(
  `Ниже — сводные карточки девяти нацпроектов технологического лидерства: реквизиты паспорта, уровень декомпозиции открытых данных и пробелы.\n\n` +
    `${JSON.stringify(settled.map((s) => ({ name: s.card.name, requisites: s.ver.requisites, decomposition: s.card.decomposition, gaps: s.card.gaps })))}\n\n` +
    `${KNOWN_UNREACHABLE}\n\n` +
    `Задача: для каждого нацпроекта, где есть пробелы, составь готовый веер запросов уровня 2 — отраслевые НПА, стратегии, дорожные карты, техрегламенты, программы корпораций — 3–6 конкретных запросов на проект. ` +
    `Каждый запрос формулируй так, чтобы он сразу выполнялся веб-поиском, и указывай в тексте запроса доступную площадку, если она важна. В comment раздели: что веер закрывает агентом, а что доступно только человеку (закрытые сайты, 403, платные базы).`,
);

const lines: string[] = [];
lines.push("# Карта источников НПТЛ — доступность и декомпозиция");
lines.push("");
lines.push("**Назначение:** фундамент дип-ресерча рамки приоритетов — где брать паспорта, показатели, отраслевые задачи и барьеры для девяти нацпроектов технологического лидерства. Собрано агентами, реквизиты каждого паспорта сверены минимум по двум независимым копиям.");
lines.push("");
lines.push(`**Среда:** закрыты government.ru, publication.pravo.gov.ru, minzdrav.gov.ru, rg.ru, pnp.ru, fso.gov.ru. 403 на программный запрос: gisp.gov.ru, mcx.gov.ru (браузерный эшелон). Работают: consultant.ru, legalacts.ru, base.garant.ru, docs.cntd.ru, нтр.рф, национальныепроекты.рф, fcntp.ru, nti2035.ru, minpromtorg.gov.ru.`);
lines.push("");
lines.push("## Сводная таблица");
lines.push("");
lines.push("| Нацпроект | Реквизиты паспорта | Верификация | Федпроектов | Декомпозиция из открытых источников |");
lines.push("|---|---|---|---|---|");
for (const s of settled) {
  lines.push(`| ${s.card.name} | ${s.ver.requisites.replace(/\|/g, "/")} | ${s.ver.confirmed ? "✅ 2 копии" : "⚠️ не подтверждено"} | ${s.card.fps.length} | ${s.card.decomposition.replace(/\|/g, "/")} |`);
}
lines.push("");
for (const s of settled) {
  lines.push(`## ${s.card.name}`);
  lines.push("");
  lines.push(`- **Реквизиты паспорта:** ${s.ver.requisites} (${s.ver.checkedWith})`);
  lines.push(`- **Федеральные проекты:** ${s.card.fps.length > 0 ? s.card.fps.join("; ") : "не собраны"}`);
  lines.push(`- **Показатели:** ${s.card.indicators}`);
  lines.push(`- **Декомпозиция:** ${s.card.decomposition}`);
  if (s.card.mirrors.length > 0) {
    lines.push(`- **Проверенные источники:**`);
    for (const m of s.card.mirrors) {
      lines.push(`  - ${m.kind} — ${m.url} — ${m.note}`);
    }
  }
  if (s.card.industryDocs.length > 0) {
    lines.push(`- **Отраслевые документы:** ${s.card.industryDocs.join("; ")}`);
  }
  if (s.card.gaps.length > 0) {
    lines.push(`- **Пробелы:** ${s.card.gaps.join("; ")}`);
  }
  lines.push("");
}
lines.push("## Веер добора уровня 2 (по пробелам)");
lines.push("");
lines.push(gapPlan.comment);
lines.push("");
for (const g of gapPlan.groups) {
  lines.push(`### ${g.nptl}`);
  for (const q of g.queries) {
    lines.push(`- ${q}`);
  }
  lines.push("");
}

const mapMd = lines.join("\n");

try {
  await artifact.markdown("nptl-map", mapMd, {
    title: "Карта источников НПТЛ",
    description: "Девять нацпроектов: реквизиты паспортов (сверены по двум копиям), федпроекты, показатели, декомпозиция и веер добора уровня 2.",
    primary: true,
  });
} catch (e) {
  const fixer = agent("публикация-карты", {
    system: "Ты — субагент публикации. Записывай файл в рабочую папку. Ничего другого не делай.",
  });
  await fixer.ask(
    `Запиши следующий markdown в файл out/nptl-sources-map.md в рабочей папке (создай папку out при необходимости):\n\n${mapMd}`,
  );
  await artifact.file("nptl-map-file", "out/nptl-sources-map.md", {
    title: "Карта источников НПТЛ",
    description: "Девять нацпроектов: реквизиты, федпроекты, показатели, декомпозиция, веер добора.",
  });
}

const findings: WorkflowReport["findings"] = [];
for (const s of settled) {
  if (!s.ver.confirmed) {
    findings.push({
      where: s.card.name,
      what: `Реквизиты паспорта не подтверждены двумя копиями: ${s.ver.requisites}`,
      evidence: s.ver.checkedWith,
      status: "unconfirmed",
      severity: "high",
    });
  }
  if (s.card.gaps.length > 0) {
    findings.push({
      where: s.card.name,
      what: "Открытых данных недостаточно для связки «криттехнология → барьер → вызов»",
      evidence: s.card.gaps.join("; "),
      status: "unconfirmed",
      severity: "medium",
    });
  }
}

return {
  conclusion: `Карта источников по ${settled.length} НПТЛ собрана: реквизиты паспортов сверены по двум независимым копиям у ${settled.filter((s) => s.ver.confirmed).length} из ${settled.length} проектов, для остальных зафиксирован неподтверждённый статус. Составлена сводная карта (паспорта, федпроекты, показатели, уровень декомпозиции) и веер добора уровня 2 по пробелам.`,
  findings: findings,
  verified: [
    "каждый реквизит паспорта проверен отдельным верификатором минимум по двум независимым площадкам-копиям",
    "каждая ссылка в карте была открыта исследователем, статус открытия зафиксирован в note",
  ],
  notCovered: [
    "первоисточники government.ru и publication.pravo.gov.ru недоступны из среды — официальная публикация не сверялась, только зеркала",
    "gisp.gov.ru и mcx.gov.ru отдают 403 на программный запрос — их содержимое не собрано (браузерный эшелон)",
    "формулировки барьеров уровня отраслевых стратегий собираются отдельным веером (фаза 2 даёт только запросы, не сами документы)",
  ],
};