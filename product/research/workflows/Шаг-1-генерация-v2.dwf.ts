interface TaskSummary {
  file: string; title: string; segment: string; mother: string; source: string; grade: string;
}
interface GenResult { written: TaskSummary[]; notes: string }
interface ValResult { updated: TaskSummary[]; regen: string[]; notes: string }
interface WorkflowReport {
  conclusion: string;
  findings: { where: string; what: string; evidence: string; status: "verified" | "unconfirmed"; severity: "low" | "medium" | "high" }[];
  verified: string[]; notCovered: string[];
}

const T = "product/workspace/1-tasks/";
const CTX = "product/workspace/0-context/";

artifact.board("portfolio", {
  key: "file", status: "status",
  columns: ["сгенерирована", "проверена", "в резерве", "готова"],
  cardTitle: "title",
});

// Контекст ужат: только то, что нужно генератору; полный текст — в файлах, генератор читает сам.
const COMMON =
  "Контекст (читай файлы сам): рамка+барьеры — " + CTX + "04-priorities-frame.md; партнёры и их зоны — " + CTX + "05-partner-requests-registry.md; НТЗ КИУ (компетенции, ограничения, направления подготовки) — " + CTX + "06-university-research-base.md.\n" +
  "Правила: 1) сегмент задачи — только из перечня паспорта (нейроассистенты / нейрообразование / нейрокоммуникации и маркетинг / спорт и здоровье); сквозной ИИ — способ решения, не сегмент. 2) Название — открытый вызов, без готового решения. 3) Покупатель: подтверждённых запросов партнёров НЕТ — «кандидат в покупатели» или «первый покупатель не определён (задача из НТЗ вуза)»; не приписывай заказов. 4) Решение обобщаемо на сегмент, без vendor-lock. 5) Реализуемость за 3 месяца силами студенческой команды (+1 TRL/MRL): не НИОКР сверху, не рутина снизу. 6) Роли — из направлений КИУ (06); опора — ИИ-софт+данные+психология/педагогика/право; НЕ опираться на патенты и аппаратные нейроинтерфейсы. 7) РИД: ПО/БД/методика. 8) Не дублируй материнские концепции прошлой волны (перечень в 04, раздел барьеров, и в файле 03). 9) Файл задачи: " + T + "NN-slug.md, шапка «Тип · Версия 1.0 · Дата 09.10.2026 · Заполнил: генератор Шага 1», 13 полей шаблона 01, затем «## Валидация»: 5 вердиктов (соответствует/условно/не соответствует + обоснование ссылкой на контекст) и градация: высокое (все 5 соответствуют) / проходное (≤1 «условно») / в резерв (2+ «условно» или любой «не соответствует»). Будь честен: разные задачи — разные градации. Каждая задача — отдельный файл; не редактируй ничего вне " + T + ".";

interface Spec { id: string; segment: string; range: string; quota: number; sources: string }
const SPECS: Spec[] = [
  { id: "нейроассистенты", segment: "Нейроассистенты", range: "01–13", quota: 13,
    sources: "Источники: карта барьеров 04 (строка про рутинную интерпретацию узкоспециальных записей), зоны партнёров 04/05 (МСП-сервисы, цифровые платформы: ИТ-парк, Фонд поддержки предпринимательства РТ, Харт Диджитал, ПАРНАС ИТ), НТЗ 06 (лаборатория машинного обучения, стартап-портфель как контекст)." },
  { id: "нейрообразование", segment: "Нейрообразование", range: "14–25", quota: 12,
    sources: "Источники: карта барьеров 04 (персонализация обучения; тренажёрная среда дефицитных навыков), НТЗ 06 (лаборатории Эдунет «Цифровой океан», цифровая педагогика, дефектология, инклюзия), партнёр НКО.ПРО (b2g, доступность образования)." },
  { id: "нейрокоммуникации", segment: "Нейрокоммуникации и маркетинг", range: "26–35", quota: 10,
    sources: "Источники: карта барьеров 04 (поведенческая аналитика МСП; отраслевые данные без прогнозных сценариев), партнёры 05 (ИВФ РТ — венчурная аналитика, Казанская Оценочная, Метриум — недвижимость, СКАТ — товары, СНК Зилант — бизнес-модели), сегмент 3 паспорта АП (прогнозирование поведенческих эффектов, СППР). Нейромаркетинг — на поведенческих данных, без ЭЭГ-аппаратуры." },
  { id: "спорт-здоровье", segment: "Спорт и здоровье", range: "36–45", quota: 10,
    sources: "Источники: карта барьеров 04 (резервы здоровья; этико-правовой контур мед-ИИ), партнёры 05 (КЛИНИКА МЕДЕЛ, СООБЩЕСТВО ВРАЧИ СТРАНЫ — Healthnet/данные; СКАТ — спорт), НТЗ 06 (стартапы NutriLog и др. как контекст). Мед-ИИ — софт/данные/право, без клинических утверждений." },
];

phase("Генерируем 45 задач по сегментам параллельно");

const gens = await Promise.all(
  SPECS.map(async (s) => {
    const g = agent("генератор-" + s.id, {
      system: "Ты — методолог генерации проектных задач для студенческого акселератора. Работаешь строго в рамке контекста: не выдумываешь партнёров, запросы, реквизиты. Пишешь по-русски плотным деловым стилем, лаконично. Файлы создаёшь только в product/workspace/1-tasks/.",
    });
    const res = await g.ask<GenResult>(
      "Сгенерируй " + s.quota + " задач для сегмента «" + s.segment + "», номера файлов " + s.range + " (по одной на файл).\n" + s.sources + "\n\n" + COMMON + "\n\nВерни JSON: written (file, title, segment, mother, source, grade) и notes.",
    );
    for (const t of res.written) report({ ...t, status: "сгенерирована" }, "portfolio");
    log("«" + s.segment + "»: задач " + res.written.length + ".");
    return { spec: s, gen: g, res: res };
  }),
);

phase("Проверяем портфель общим валидатором");

const validator = agent("валидатор-портфеля", {
  system: "Ты — строгий независимый валидатор портфеля задач (авторы — другие агенты). Единая калибровка вердиктов по всем сегментам. Читаешь файлы и контекст сам. Правишь градации в файлах, где автор ошибся или завысил.",
});
const val = await validator.ask<ValResult>(
  "Прочитай все 45 задач в " + T + " и контекст (04, 05, 06).\n" +
  "По каждой: проверь 5 критериев (К1 приоритеты из рамки 04; К2 компетенции из 06; К3 реализуемость за 3 месяца; К4 покупатель без vendor-lock и без приписанных заказов; К5 образовательный потенциал), сегмент из перечня паспорта, название без готового решения. Исправь завышения в файлах.\n" +
  "Верни JSON: updated (сводки всех задач с итоговыми grade), regen (файлы с градацией «в резерв»), notes.",
);
for (const t of val.updated) {
  report({ ...t, status: t.grade === "в резерв" ? "в резерве" : "проверена" }, "portfolio");
}
log("Проверено " + val.updated.length + ", в резерве " + val.regen.length + ".");

phase("Перегенерируем задачи в резерве (1 цикл)");

if (val.regen.length > 0) {
  const feedback = await validator.ask<string>(
    "Сформулируй для генераторов короткую причину отбраковки каждой задачи: " + JSON.stringify(val.regen),
  );
  const regen = await Promise.all(
    SPECS.map(async (s) => {
      const files = val.regen.filter((f) => {
        const [a, b] = s.range.split("–").map(Number);
        const n = parseInt(f.slice(0, 2), 10);
        return n >= a && n <= b;
      });
      if (files.length === 0) return null;
      const g = agent("регенератор-" + s.id, {
        system: "Ты — методолог генерации проектных задач. Перезаписываешь отбракованные файлы задач. Работаешь только в " + T + ".",
      });
      return await g.ask<GenResult>(
        "Перегенерируй задачи (замени содержимое файлов, номера и имена сохрани): " + JSON.stringify(files) + "\n" +
        "Причины отбраковки: " + feedback + "\n" + COMMON + "\nВерни written и notes.",
      );
    }),
  );
  const written = regen.filter(Boolean).flatMap((r) => r!.written);
  const recheck = await validator.ask<ValResult>(
    "Генераторы заменили файлы: " + JSON.stringify(written.map((w) => w.file)) + "\nПроверь их заново теми же правилами. Верни updated и regen (только всё ещё «в резерв»).",
  );
  // замена обновлённых сводок в общем списке
  const map = new Map(recheck.updated.map((u) => [u.file, u]));
  val.updated = val.updated.map((u) => map.get(u.file) ?? u);
  val.regen = recheck.regen;
  for (const t of recheck.updated) {
    report({ ...t, status: t.grade === "в резерв" ? "в резерве" : "проверена" }, "portfolio");
  }
  log("После перегенерации в резерве " + recheck.regen.length + ".");
}

phase("Собираем сводку портфеля и публикуем");

const assembler = agent("сборка-сводки", {
  system: "Ты — методолог. Собираешь сводку портфеля задач: читаешь файлы, группируешь, считаешь. Пишешь по-русски. Редактируешь только файл сводки.",
});
await assembler.ask(
  "Прочитай все файлы задач в " + T + " (кроме сводки). Запиши " + T + "00-сводка-портфеля.md: итог и градации; распределение по 4 сегментам паспорта АП; материнские концепции (2+ задач — с файлами); по каждой задаче: файл · название · сегмент · концепция · источник · градация; критерии отбора (сколько сгенерировано, отбраковано, резерв и причины); пробелы контекста, повлиявшие на генерацию. Шапка: «Тип · Версия 1.0 · Дата 09.10.2026 · Заполнил: агент Шага 1». Понятно организатору без чтения задач.",
);
const all = val.updated;
const ready = all.filter((t) => t.grade !== "в резерв");
for (const t of ready) report({ ...t, status: "готова" }, "portfolio");

let published = true;
try {
  await artifact.file("portfolio-summary", T + "00-сводка-портфеля.md", {
    title: "Сводка портфеля проектных задач (Шаг 1)",
    description: ready.length + " готовых задач; распределение по сегментам, материнские концепции, градации, резерв.",
    primary: true,
  });
} catch {
  published = false;
}

const reserve = all.filter((t) => t.grade === "в резерв").map((t) => t.file);
return {
  conclusion: "Шаг 1 выполнен (v2-режим: 4 генератора + общий валидатор, 1 цикл перегенерации): " + ready.length + " из 45 задач готовы в product/workspace/1-tasks/ (высокое " + all.filter((t) => t.grade === "высокое").length + ", проходное " + all.filter((t) => t.grade === "проходное").length + ", в резерве " + reserve.length + "). Сводка: 00-сводка-портфеля.md" + (published ? " (опубликована артефактом)." : " (файл в репозитории)."),
  findings: reserve.map((f) => ({ where: T + f, what: "Задача осталась в резерве после цикла перегенерации — судьбу решает организатор.", evidence: "валидация в файле задачи", status: "verified", severity: "low" })),
  verified: ["каждая задача прошла независимую валидацию по 5 критериям (валидатор — не автор)", "сегменты сверены с закрытым перечнем паспорта АП", "единая калибровка вердиктов одним валидатором на весь портфель"],
  notCovered: ["официальный слой рамки Нейронет-НПТЛ не собирался (барьеры — гипотезы)", "сквозная дедупликация между сегментами ограничена списком материнских концепций прошлой волны"],
};