interface Barrier {
  /** Барьер в измеримой форме: «не достигается X при условиях Y; параметр Z: база → цель». Оценочные формулировки запрещены. */
  barrier: string;
  /** Какая криттехнология или показатель НПТЛ стоит за барьером. */
  link: string;
  /** Канал В1–В7: документ, ссылка, статус/дата. */
  source: string;
  /** Кто страдает/платит сейчас: запрос партнёра, закупка НИОКР, программа — с ссылкой. Пусто = не найдено. */
  industry: string;
  /** Уровень пирамиды: ресурсы / жизненный цикл / система. */
  level: string;
  /** confirmed: две опоры / hypothesis: только официальная. */
  status: string;
}

interface ChannelReport {
  /** Канал: В1…В7 + человеческое название. */
  channel: string;
  /** Найденные документы канала: название, реквизиты, ссылка, что даёт, эшелон доступа. */
  documents: string[];
  /** Собранные из канала барьер-кандидаты. */
  barriers: Barrier[];
  /** Что не собрано и почему (эшелон, бюджет). */
  gaps: string;
}

